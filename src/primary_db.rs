use super::*;

pub(crate) const PRIMARY_SCHEMA_SQL: &str = r#"
CREATE SCHEMA IF NOT EXISTS cvm_core;
CREATE SCHEMA IF NOT EXISTS cvm_activity;
CREATE SCHEMA IF NOT EXISTS cvm_stats;
CREATE SCHEMA IF NOT EXISTS cvm_archive;
CREATE SCHEMA IF NOT EXISTS cvm_assets;
CREATE SCHEMA IF NOT EXISTS cvm_migration;
CREATE TABLE IF NOT EXISTS cvm_migration.schema_migrations (
    component TEXT NOT NULL,
    version BIGINT NOT NULL,
    checksum TEXT NOT NULL,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (component, version)
);
CREATE TABLE IF NOT EXISTS cvm_core.state_kv (
    state_key TEXT PRIMARY KEY,
    state_value JSONB NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS cvm_activity.proxy_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoke_id TEXT NOT NULL UNIQUE,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    method TEXT NOT NULL,
    request_path TEXT NOT NULL,
    status_code INTEGER,
    request_bytes BIGINT NOT NULL DEFAULT 0,
    response_bytes BIGINT NOT NULL DEFAULT 0,
    duration_ms DOUBLE PRECISION,
    error TEXT
);
CREATE INDEX IF NOT EXISTS cvm_activity_proxy_requests_occurred_at_idx
    ON cvm_activity.proxy_requests (occurred_at DESC);
"#;
const PRIMARY_SCHEMA_VERSION: i64 = 3;
const PRIMARY_SCHEMAS: [&str; 6] = [
    "cvm_core",
    "cvm_activity",
    "cvm_stats",
    "cvm_archive",
    "cvm_assets",
    "cvm_migration",
];

#[derive(Debug, Clone)]
pub(crate) struct PrimaryDatabase {
    pool: sqlx::PgPool,
}

impl PrimaryDatabase {
    pub(crate) fn from_pool(pool: sqlx::PgPool) -> Self {
        Self { pool }
    }

    pub(crate) async fn connect(config: &AppConfig) -> Result<Self> {
        let url = config
            .postgres_primary_database_url
            .as_ref()
            .context("POSTGRES_PRIMARY_DATABASE_URL is required for PostgreSQL primary runtime")?;
        Self::connect_url(url, config.postgres_primary_max_connections).await
    }

    pub(crate) async fn connect_runtime(config: &AppConfig) -> Result<Self> {
        let database = Self::connect(config).await?;
        database.validate_runtime_schema().await?;
        Ok(database)
    }

    pub(crate) async fn connect_url(
        url: &PostgresDatabaseUrl,
        max_connections: u32,
    ) -> Result<Self> {
        let pool = sqlx::postgres::PgPoolOptions::new()
            .max_connections(max_connections)
            .acquire_timeout(Duration::from_secs(5))
            .connect(url.as_str())
            .await
            .context("failed to connect to PostgreSQL primary database")?;
        let database = Self { pool };
        database.verify_server_version().await?;
        Ok(database)
    }

    async fn verify_server_version(&self) -> Result<()> {
        let version: i32 = sqlx::query_scalar("SELECT current_setting('server_version_num')::int")
            .fetch_one(&self.pool)
            .await?;
        if !(180000..190000).contains(&version) {
            bail!("unsupported PostgreSQL primary version; expected 18.x");
        }
        Ok(())
    }

    pub(crate) async fn ensure_schema(&self) -> Result<()> {
        sqlx::raw_sql(PRIMARY_SCHEMA_SQL)
            .execute(&self.pool)
            .await
            .context("failed to ensure PostgreSQL primary schema")?;
        self.validate_schema_contract().await?;
        let checksum = format!("{:x}", Sha256::digest(PRIMARY_SCHEMA_SQL.as_bytes()));
        let existing_checksum: Option<String> = sqlx::query_scalar(
            "SELECT checksum FROM cvm_migration.schema_migrations WHERE component='primary-schema' AND version=$1",
        )
        .bind(PRIMARY_SCHEMA_VERSION)
        .fetch_optional(&self.pool)
        .await
        .context("failed to read PostgreSQL primary schema checksum")?;
        if let Some(existing_checksum) = existing_checksum {
            if existing_checksum != checksum {
                bail!("PostgreSQL primary schema checksum mismatch");
            }
        } else {
            sqlx::query(
                "INSERT INTO cvm_migration.schema_migrations(component,version,checksum) VALUES('primary-schema',$1,$2)",
            )
            .bind(PRIMARY_SCHEMA_VERSION)
            .bind(checksum)
            .execute(&self.pool)
            .await
            .context("failed to record PostgreSQL primary schema checksum")?;
        }
        Ok(())
    }

    pub(crate) async fn validate_runtime_schema(&self) -> Result<()> {
        self.verify_server_version().await?;
        self.validate_schema_contract().await?;
        let ledger_exists: bool =
            sqlx::query_scalar("SELECT to_regclass('cvm_migration.schema_migrations') IS NOT NULL")
                .fetch_one(&self.pool)
                .await
                .context("failed to validate PostgreSQL migration ledger")?;
        if !ledger_exists {
            bail!("required PostgreSQL migration ledger is missing");
        }
        let expected_checksum = format!("{:x}", Sha256::digest(PRIMARY_SCHEMA_SQL.as_bytes()));
        let recorded_checksum: Option<String> = sqlx::query_scalar(
            "SELECT checksum FROM cvm_migration.schema_migrations WHERE component='primary-schema' AND version=$1",
        )
        .bind(PRIMARY_SCHEMA_VERSION)
        .fetch_optional(&self.pool)
        .await
        .context("failed to validate PostgreSQL primary schema checksum")?;
        match recorded_checksum {
            Some(actual) if actual == expected_checksum => {}
            Some(_) => bail!("PostgreSQL primary schema checksum mismatch"),
            None => bail!("PostgreSQL primary schema checksum is missing"),
        }
        for schema in PRIMARY_SCHEMAS {
            let can_create: bool =
                sqlx::query_scalar("SELECT has_schema_privilege(current_user, $1, 'CREATE')")
                    .bind(schema)
                    .fetch_one(&self.pool)
                    .await
                    .with_context(|| {
                        format!("failed to validate PostgreSQL DDL privilege on schema {schema}")
                    })?;
            if can_create {
                bail!("PostgreSQL runtime role must not have CREATE on schema {schema}");
            }
        }
        let can_write_state: bool = sqlx::query_scalar(
            "SELECT has_table_privilege(current_user, 'cvm_core.state_kv', 'SELECT,INSERT,UPDATE')",
        )
        .fetch_one(&self.pool)
        .await
        .context("failed to validate PostgreSQL runtime state privileges")?;
        if !can_write_state {
            bail!("PostgreSQL runtime role lacks SELECT/INSERT/UPDATE on cvm_core.state_kv");
        }
        let can_write_proxy_requests: bool = sqlx::query_scalar(
            "SELECT has_table_privilege(current_user, 'cvm_activity.proxy_requests', 'SELECT,INSERT')",
        )
        .fetch_one(&self.pool)
        .await
        .context("failed to validate PostgreSQL proxy request privileges")?;
        if !can_write_proxy_requests {
            bail!("PostgreSQL runtime role lacks SELECT/INSERT on cvm_activity.proxy_requests");
        }
        let account_target: Option<(String, String)> = sqlx::query_as(
            "SELECT target_schema,target_table FROM cvm_migration.object_targets targets JOIN cvm_migration.runs runs USING (run_id) WHERE targets.object_name='pool_upstream_accounts' AND runs.state IN ('verified','finalized') ORDER BY runs.updated_at DESC LIMIT 1",
        )
        .fetch_optional(&self.pool)
        .await
        .context("failed to validate PostgreSQL upstream account target")?;
        if let Some((schema, table)) = account_target {
            let qualified = format!(
                "\"{}\".\"{}\"",
                schema.replace('"', "\"\""),
                table.replace('"', "\"\"")
            );
            let can_write_accounts: bool = sqlx::query_scalar(
                "SELECT has_table_privilege(current_user, $1, 'SELECT,UPDATE,DELETE')",
            )
            .bind(qualified)
            .fetch_one(&self.pool)
            .await
            .context("failed to validate PostgreSQL upstream account privileges")?;
            if !can_write_accounts {
                bail!(
                    "PostgreSQL runtime role lacks SELECT/UPDATE/DELETE on the migrated upstream account table"
                );
            }
        }
        let targets: Vec<(String, String, String, String)> = sqlx::query_as(
            "SELECT targets.object_name,targets.target_schema,targets.target_table,columns.column_name
             FROM cvm_migration.object_targets targets
             JOIN cvm_migration.runs runs USING (run_id)
             JOIN cvm_migration.object_columns columns USING (run_id, object_name)
             WHERE runs.state IN ('verified','finalized')
               AND columns.primary_key_position > 0
               AND columns.declared_type ILIKE ANY (ARRAY['%INT%','%SERIAL%'])
             ORDER BY runs.updated_at DESC, targets.object_name, columns.primary_key_position",
        )
        .fetch_all(&self.pool)
        .await
        .context("failed to validate PostgreSQL materialized target relations")?;
        let mut checked_targets = std::collections::HashSet::new();
        for (object_name, schema, table, column) in targets {
            let target_key = format!("{schema}.{table}.{column}");
            if !checked_targets.insert(target_key) {
                continue;
            }
            let qualified = format!(
                "\"{}\".\"{}\"",
                schema.replace('"', "\"\""),
                table.replace('"', "\"\"")
            );
            let exists: bool = sqlx::query_scalar("SELECT to_regclass($1) IS NOT NULL")
                .bind(&qualified)
                .fetch_one(&self.pool)
                .await
                .with_context(|| {
                    format!("failed to validate PostgreSQL target relation {qualified}")
                })?;
            if !exists {
                bail!("PostgreSQL materialized target relation is missing: {qualified}");
            }
            let sequence_name: Option<String> =
                sqlx::query_scalar("SELECT pg_get_serial_sequence($1,$2)")
                    .bind(format!("{schema}.{table}"))
                    .bind(&column)
                    .fetch_one(&self.pool)
                    .await
                    .with_context(|| {
                        format!("failed to validate sequence for migrated object {object_name}")
                    })?;
            if sequence_name.is_none() {
                bail!(
                    "PostgreSQL migrated integer primary key has no identity sequence: {qualified}.{column}"
                );
            }
            let sequence_name = sequence_name.expect("checked above");
            let can_use_sequence: bool = sqlx::query_scalar(
                "SELECT has_sequence_privilege(current_user, $1, 'USAGE,SELECT,UPDATE')",
            )
            .bind(&sequence_name)
            .fetch_one(&self.pool)
            .await
            .with_context(|| {
                format!("failed to validate sequence privileges for {qualified}.{column}")
            })?;
            if !can_use_sequence {
                bail!("PostgreSQL runtime role lacks sequence privileges for {qualified}.{column}");
            }
        }
        Ok(())
    }

    async fn validate_schema_contract(&self) -> Result<()> {
        for schema in PRIMARY_SCHEMAS {
            let exists: bool = sqlx::query_scalar("SELECT to_regnamespace($1) IS NOT NULL")
                .bind(schema)
                .fetch_one(&self.pool)
                .await
                .with_context(|| format!("failed to validate PostgreSQL schema {schema}"))?;
            if !exists {
                bail!("required PostgreSQL primary schema is missing: {schema}");
            }
            let can_use: bool =
                sqlx::query_scalar("SELECT has_schema_privilege(current_user, $1, 'USAGE')")
                    .bind(schema)
                    .fetch_one(&self.pool)
                    .await
                    .with_context(|| {
                        format!("failed to validate PostgreSQL privileges on schema {schema}")
                    })?;
            if !can_use {
                bail!("PostgreSQL primary role lacks USAGE on schema {schema}");
            }
        }
        let state_table_exists: bool =
            sqlx::query_scalar("SELECT to_regclass('cvm_core.state_kv') IS NOT NULL")
                .fetch_one(&self.pool)
                .await
                .context("failed to validate PostgreSQL primary state table")?;
        if !state_table_exists {
            bail!("required PostgreSQL primary table is missing: cvm_core.state_kv");
        }
        let proxy_table_exists: bool =
            sqlx::query_scalar("SELECT to_regclass('cvm_activity.proxy_requests') IS NOT NULL")
                .fetch_one(&self.pool)
                .await
                .context("failed to validate PostgreSQL primary proxy request table")?;
        if !proxy_table_exists {
            bail!("required PostgreSQL primary table is missing: cvm_activity.proxy_requests");
        }
        Ok(())
    }

    pub(crate) fn pool(&self) -> &sqlx::PgPool {
        &self.pool
    }

    pub(crate) async fn get_json_state(&self, key: &str) -> Result<Option<serde_json::Value>> {
        let value: Option<sqlx::types::Json<serde_json::Value>> =
            sqlx::query_scalar("SELECT state_value FROM cvm_core.state_kv WHERE state_key=$1")
                .bind(key)
                .fetch_optional(&self.pool)
                .await
                .context("failed to read PostgreSQL primary JSON state")?;
        Ok(value.map(|value| value.0))
    }

    pub(crate) async fn put_json_state(&self, key: &str, value: &serde_json::Value) -> Result<()> {
        sqlx::query(
            "INSERT INTO cvm_core.state_kv(state_key,state_value) VALUES($1,$2) \
             ON CONFLICT(state_key) DO UPDATE SET state_value=EXCLUDED.state_value,updated_at=now()",
        )
        .bind(key)
        .bind(sqlx::types::Json(value))
        .execute(&self.pool)
        .await
        .context("failed to write PostgreSQL primary JSON state")?;
        Ok(())
    }
}
